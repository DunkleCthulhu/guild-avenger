local language = "ukUA"

function addon.InitLanguage(hadSettings)
    local saved = GuildAvengerDB.language
    if not translations[saved] then
        saved = (hadSettings or GetLocale() == "ukUA") and "ukUA" or "enUS"
    end
    language = saved
    GuildAvengerDB.language = saved
end

function addon.Language()
    return language
end

function addon.TextFor(locale, key, ...)
    local text = translations[locale][key]
    if select("#", ...) > 0 then
        return text:format(...)
    end
    return text
end

function addon.Text(key, ...)
    return addon.TextFor(language, key, ...)
end
